"""Run output, export, and discovered-paper API routes."""

from datetime import datetime
from typing import Any
from uuid import UUID

from fastapi import APIRouter, Depends, HTTPException, Query
from fastapi.responses import Response
from pydantic import BaseModel, Field
from structlog import get_logger

import apps.api.database as db
from apps.api.auth import get_current_user
from apps.api.tenancy import WorkspaceContext
from libs.schemas.run import RunStatus
from services.export import (
    generate_bibtex_export,
    generate_csv_export,
    generate_json_export,
    generate_markdown_report,
)

logger = get_logger(__name__)
router = APIRouter(prefix="/api/v1/runs", tags=["run-results"])


class HypothesisResponse(BaseModel):
    """Response for a hypothesis."""

    id: UUID
    run_id: UUID
    title: str
    statement: str
    type: str
    novelty_score: float
    feasibility_score: float
    evidence_score: float
    risk_score: float
    status: str
    created_at: datetime


class ExportRequest(BaseModel):
    """Request to export run results."""

    formats: list[str] = Field(default=["markdown"], description="Export formats")


class ExportResponse(BaseModel):
    """Response for export request."""

    run_id: UUID
    exports: list[dict[str, Any]]


@router.get("/{run_id}/hypotheses", response_model=list[HypothesisResponse])
async def get_run_hypotheses(
    run_id: UUID,
    user: dict[str, Any] = Depends(get_current_user),
) -> list[dict[str, Any]]:
    """Get hypotheses generated by a research run."""
    ctx = WorkspaceContext.from_user(user)
    try:
        run = await db.get_run(run_id, workspace_id=ctx.workspace_id)
    except Exception as exc:
        logger.error("get_hypotheses_run_check_failed", run_id=str(run_id), error=str(exc))
        raise HTTPException(status_code=500, detail="Failed to retrieve run") from exc

    if run is None:
        raise HTTPException(status_code=404, detail="Run not found")

    try:
        return await db.list_hypotheses(run_id)
    except Exception as exc:
        logger.error("list_hypotheses_failed", run_id=str(run_id), error=str(exc))
        raise HTTPException(status_code=500, detail="Failed to list hypotheses") from exc


@router.post("/{run_id}/export", response_model=ExportResponse)
async def export_run_results(
    run_id: UUID,
    request: ExportRequest,
    user: dict[str, Any] = Depends(get_current_user),
) -> dict[str, Any]:
    """Export results of a completed research run."""
    ctx = WorkspaceContext.from_user(user)
    try:
        run = await db.get_run(run_id, workspace_id=ctx.workspace_id)
    except Exception as exc:
        logger.error("export_run_get_failed", run_id=str(run_id), error=str(exc))
        raise HTTPException(status_code=500, detail="Failed to retrieve run") from exc

    if run is None:
        raise HTTPException(status_code=404, detail="Run not found")
    if run["status"] != RunStatus.COMPLETED.value:
        raise HTTPException(
            status_code=400,
            detail=f"Cannot export run in status: {run['status']}",
        )

    exports = []
    for fmt in request.formats:
        if fmt in ["markdown", "json", "csv", "bibtex"]:
            exports.append({
                "format": fmt,
                "status": "generated",
                "url": f"/api/v1/runs/{run_id}/downloads/{fmt}",
            })

    return {"run_id": run_id, "exports": exports}


@router.get("/{run_id}/downloads/{format}")
async def download_export(
    run_id: UUID,
    format: str,
    user: dict[str, Any] = Depends(get_current_user),
) -> Response:
    """Download an export file for a research run."""
    valid_formats = {"markdown", "json", "csv", "bibtex"}
    if format not in valid_formats:
        raise HTTPException(
            status_code=400,
            detail=f"Invalid format: {format}. Must be one of: {', '.join(valid_formats)}",
        )

    ctx = WorkspaceContext.from_user(user)
    try:
        run = await db.get_run(run_id, workspace_id=ctx.workspace_id)
    except Exception as exc:
        logger.error("download_export_get_failed", run_id=str(run_id), error=str(exc))
        raise HTTPException(status_code=500, detail="Failed to retrieve run") from exc

    if run is None:
        raise HTTPException(status_code=404, detail="Run not found")

    try:
        papers = await db.list_papers_by_run(run_id, limit=200, offset=0)
        hypotheses = await db.list_hypotheses(run_id)
    except Exception as exc:
        logger.error("download_export_data_failed", run_id=str(run_id), error=str(exc))
        raise HTTPException(status_code=500, detail="Failed to fetch run data") from exc

    if format == "markdown":
        try:
            events = await db.list_events(run_id, limit=20, offset=0)
        except Exception:
            events = []
        content = await generate_markdown_report(run, hypotheses, papers, events)
        return Response(
            content=content.encode("utf-8"),
            media_type="text/markdown; charset=utf-8",
            headers={
                "Content-Disposition": f"attachment; filename=\"research-report-{run_id}.md\"",
            },
        )

    if format == "json":
        content = await generate_json_export(run, hypotheses, papers)
        return Response(
            content=content.encode("utf-8"),
            media_type="application/json; charset=utf-8",
            headers={
                "Content-Disposition": f"attachment; filename=\"research-export-{run_id}.json\"",
            },
        )

    if format == "csv":
        content = await generate_csv_export(papers)
        return Response(
            content=content.encode("utf-8"),
            media_type="text/csv; charset=utf-8",
            headers={
                "Content-Disposition": f"attachment; filename=\"papers-{run_id}.csv\"",
            },
        )

    if format == "bibtex":
        content = await generate_bibtex_export(papers)
        return Response(
            content=content.encode("utf-8"),
            media_type="application/x-bibtex; charset=utf-8",
            headers={
                "Content-Disposition": f"attachment; filename=\"references-{run_id}.bib\"",
            },
        )

    raise HTTPException(status_code=400, detail="Unsupported format")


@router.get("/{run_id}/papers")
async def get_run_papers(
    run_id: UUID,
    limit: int = Query(50, ge=1, le=200),
    offset: int = Query(0, ge=0),
    user: dict[str, Any] = Depends(get_current_user),
) -> dict[str, Any]:
    """Get papers discovered in a research run."""
    ctx = WorkspaceContext.from_user(user)
    try:
        run = await db.get_run(run_id, workspace_id=ctx.workspace_id)
    except Exception as exc:
        logger.error("get_papers_run_check_failed", run_id=str(run_id), error=str(exc))
        raise HTTPException(status_code=500, detail="Failed to retrieve run") from exc

    if run is None:
        raise HTTPException(status_code=404, detail="Run not found")

    try:
        total = await db.count_papers_by_run(run_id)
        papers = await db.list_papers_by_run(run_id, limit=limit, offset=offset)
    except Exception as exc:
        logger.error("list_papers_failed", run_id=str(run_id), error=str(exc))
        raise HTTPException(status_code=500, detail="Failed to list papers") from exc

    return {
        "run_id": str(run_id),
        "total": total,
        "papers": papers,
    }
